from __future__ import annotations

# Avito separates men's clothing into three taxonomy levels:
# GoodsType="Мужская одежда", a broad Apparel group and a narrower ApparelType.
APPAREL_FIELDS = {
    "Куртка": ("Верхняя одежда", "Демисезонные куртки"),
    "Ветровка": ("Верхняя одежда", "Лёгкие куртки и ветровки"),
    "Пуховик": ("Верхняя одежда", "Зимние куртки и пуховики"),
    "Пальто": ("Верхняя одежда", "Пальто"),
    "Жилет": ("Верхняя одежда", "Жилеты"),
    "Худи": ("Кофты и футболки", "Толстовки"),
    "Толстовка": ("Кофты и футболки", "Толстовки"),
    "Олимпийка": ("Кофты и футболки", "Толстовки"),
    "Футболка": ("Кофты и футболки", "Футболки"),
    "Поло": ("Кофты и футболки", "Футболки"),
    "Лонгслив": ("Кофты и футболки", "Футболки"),
    "Джемпер": ("Кофты и футболки", "Свитеры"),
    "Кардиган": ("Кофты и футболки", "Свитеры"),
    "Свитер": ("Кофты и футболки", "Свитеры"),
    "Пуловер": ("Кофты и футболки", "Свитеры"),
    "Водолазка": ("Кофты и футболки", "Свитеры"),
    "Рубашка": ("Рубашки", "Рубашки"),
    "Шорты": ("Шорты", "Шорты"),
    "Штаны": ("Брюки", "Брюки"),
    "Костюм": ("Пиджаки и костюмы", "Костюмы"),
    "Домашняя одежда": ("Другое", "Домашняя одежда"),
}


def apparel_fields(product_type: str, product_text: str = "") -> tuple[str, str]:
    if product_type == "Куртка":
        text = product_text.casefold()
        keyword_types = (
            (("пухов", "puffer", "down jacket", "утеплен", "утеплён", "зимн"),
             "Зимние куртки и пуховики"),
            (("ветров", "windbreaker", "лёгк", "легк"), "Лёгкие куртки и ветровки"),
            (("бомбер", "bomber"), "Бомберы"),
            (("парка", "parka"), "Парки"),
            (("кожан", "leather"), "Кожаные куртки"),
            (("джинс", "denim"), "Джинсовые куртки"),
        )
        for keywords, mapped_type in keyword_types:
            if any(keyword in text for keyword in keywords):
                return "Верхняя одежда", mapped_type
    return APPAREL_FIELDS.get(product_type, ("Другое", "Другое"))
